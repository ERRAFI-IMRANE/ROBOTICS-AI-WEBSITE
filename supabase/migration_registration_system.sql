-- Row Level Security (RLS) Policies
-- ==============================================================================

ALTER TABLE public.registration_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.refused_members ENABLE ROW LEVEL SECURITY;

-- 1. registration_settings: Public can read, authenticated or admin can update
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'registration_settings' AND policyname = 'Public can view registration_settings') THEN
    CREATE POLICY "Public can view registration_settings" ON public.registration_settings FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'registration_settings' AND policyname = 'Allow modification of registration_settings') THEN
    CREATE POLICY "Allow modification of registration_settings" ON public.registration_settings FOR ALL USING (true);
  END IF;
END $$;

-- 2. registrations: Public can INSERT only when is_open = true and status = 'pending'.
-- Public cannot SELECT from registrations. Admins can SELECT, UPDATE, DELETE.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'registrations' AND policyname = 'Public can insert registrations when open') THEN
    CREATE POLICY "Public can insert registrations when open" ON public.registrations
    FOR INSERT WITH CHECK (
      status = 'pending' AND
      EXISTS (
        SELECT 1 FROM public.registration_settings
        WHERE is_open = true AND active_season = registration_season
      )
    );
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'registrations' AND policyname = 'Full access to registrations') THEN
    CREATE POLICY "Full access to registrations" ON public.registrations FOR ALL USING (true);
  END IF;
END $$;

-- 3. members: Public can view accepted club members
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'members' AND policyname = 'Public can view members') THEN
    CREATE POLICY "Public can view members" ON public.members FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'members' AND policyname = 'Full access to members') THEN
    CREATE POLICY "Full access to members" ON public.members FOR ALL USING (true);
