-- Atomic Acceptance: copies from registrations into members, then deletes from registrations
CREATE OR REPLACE FUNCTION public.accept_club_registration(p_registration_id BIGINT)
RETURNS public.members
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_reg public.registrations%ROWTYPE;
  v_member public.members%ROWTYPE;
BEGIN
  -- 1. Fetch the application
  SELECT * INTO v_reg FROM public.registrations WHERE id = p_registration_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Registration application with ID % not found', p_registration_id;
  END IF;

  -- 2. Insert into members
  INSERT INTO public.members (
    full_name,
    email,
    phone,
    department,
    filiere,
    years_of_study,
    message,
    registration_season,
    joined_at
  ) VALUES (
    v_reg.full_name,
    v_reg.email,
    v_reg.phone,
    v_reg.department,
    v_reg.filiere,
    v_reg.years_of_study,
    v_reg.message,
    v_reg.registration_season,
    NOW()
  )
  RETURNING * INTO v_member;

  -- 3. Delete from registrations only after successful insertion
  DELETE FROM public.registrations WHERE id = p_registration_id;

  RETURN v_member;
END;
$$;

-- Atomic Refusal: copies from registrations into refused_members, then deletes from registrations
CREATE OR REPLACE FUNCTION public.refuse_club_registration(p_registration_id BIGINT, p_reason TEXT DEFAULT NULL)
RETURNS public.refused_members
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_reg public.registrations%ROWTYPE;
  v_refused public.refused_members%ROWTYPE;
BEGIN
  -- 1. Fetch the application
  SELECT * INTO v_reg FROM public.registrations WHERE id = p_registration_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Registration application with ID % not found', p_registration_id;
  END IF;

  -- 2. Insert into refused_members
  INSERT INTO public.refused_members (
    original_registration_id,
    full_name,
    email,
    phone,
    department,
    filiere,
    years_of_study,
    message,
    registration_season,
    refusal_reason,
    refused_at
  ) VALUES (
    v_reg.id,
    v_reg.full_name,
    v_reg.email,
    v_reg.phone,
    v_reg.department,
    v_reg.filiere,
    v_reg.years_of_study,
    v_reg.message,
    v_reg.registration_season,
    p_reason,
    NOW()
  )
  RETURNING * INTO v_refused;

  -- 3. Delete from registrations only after successful insertion
  DELETE FROM public.registrations WHERE id = p_registration_id;

  RETURN v_refused;
END;
$$;

-- Safe Season Closing: checks if pending registrations exist before closing
CREATE OR REPLACE FUNCTION public.close_registration_season()
RETURNS public.registration_settings
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_pending_count INT;
  v_settings public.registration_settings%ROWTYPE;
BEGIN
  -- 1. Check for pending applications
  SELECT COUNT(*) INTO v_pending_count FROM public.registrations WHERE status = 'pending';
  IF v_pending_count > 0 THEN
    RAISE EXCEPTION 'Cannot close registration: % pending application(s) exist. Please accept or refuse all applications before closing.', v_pending_count;
  END IF;

  -- 2. Close registration
  UPDATE public.registration_settings
  SET
    is_open = false,
    closed_at = NOW(),
    updated_at = NOW()
  WHERE id = 1
  RETURNING * INTO v_settings;

  RETURN v_settings;
END;
$$;
