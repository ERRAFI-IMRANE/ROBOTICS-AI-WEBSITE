-- 1. Table: registration_settings
-- Controls whether registration is open and the active season
CREATE TABLE IF NOT EXISTS public.registration_settings (
  id SERIAL PRIMARY KEY,
  is_open BOOLEAN NOT NULL DEFAULT true,
  active_season TEXT NOT NULL DEFAULT '2025-2026',
  closed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Seed initial settings row if not present
INSERT INTO public.registration_settings (id, is_open, active_season)
VALUES (1, true, '2025-2026')
ON CONFLICT (id) DO UPDATE SET
  is_open = EXCLUDED.is_open,
  active_season = EXCLUDED.active_season;

-- 2. Table: registrations (Temporary registration applications)
CREATE TABLE IF NOT EXISTS public.registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  department TEXT NOT NULL,
  filiere TEXT NOT NULL,
  years_of_study TEXT NOT NULL,
  message TEXT,
  registration_season TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT check_reg_status CHECK (status IN ('pending', 'accepted', 'refused')),
  CONSTRAINT check_reg_years CHECK (years_of_study IN ('first_year', 'second_year', 'bachelor', 'master', 'phd'))
);

CREATE INDEX IF NOT EXISTS idx_registrations_season_status ON public.registrations(registration_season, status);

-- 3. Table: members (Permanent regular club members — completely separate from team/staff)
CREATE TABLE IF NOT EXISTS public.members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  department TEXT NOT NULL,
  filiere TEXT NOT NULL,
  years_of_study TEXT NOT NULL,
  message TEXT,
  registration_season TEXT NOT NULL,
  joined_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT check_mem_years CHECK (years_of_study IN ('first_year', 'second_year', 'bachelor', 'master', 'phd'))
);

CREATE INDEX IF NOT EXISTS idx_members_season ON public.members(registration_season);

-- 4. Table: refused_members (Permanently stored refused applications)
CREATE TABLE IF NOT EXISTS public.refused_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_registration_id BIGINT,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  department TEXT NOT NULL,
  filiere TEXT NOT NULL,
  years_of_study TEXT NOT NULL,
  message TEXT,
  registration_season TEXT NOT NULL,
  refusal_reason TEXT,
  refused_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

